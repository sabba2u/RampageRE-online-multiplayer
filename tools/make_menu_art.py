"""Make the main menu's Boss Rumble icon (port extra) from the owner's art and write it into src/menu_art.h.

The game's play mode icons are two quads (MainMenu.ifc `icons`): a 128 x 128 glow (white, tinted red, or green when
chosen, by shell.c mm_icons) and over it the monster art (160 x 129 at scale 0.73). This makes both from one picture:
  art:  the picture's solid part (alpha >= 245: its own baked-in glow dropped, the menu draws the glow), 256 x 256
  glow: the art's silhouette as it sits in the glow's 128 x 128 (centred, 94 x 94), grown and blurred, white
Both are PNG bytes in the header (render_gl.c decodes them with stb_image), so the exe needs no file beside it.

Usage: python tools/make_menu_art.py [images/bossrush.png] [src/menu_art.h]
"""
import io
import sys

from PIL import Image, ImageFilter

ART = 256          # the art texture's size
GLOW = 128         # the glow texture's size (the game's)
INNER = 94         # the art's size inside the glow: 129 x 0.73


def square(im):
    box = im.getbbox() or (0, 0, im.width, im.height)
    im = im.crop(box)
    side = max(im.size)
    out = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    out.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    return out


def png_bytes(im):
    b = io.BytesIO()
    im.save(b, 'PNG', optimize=True)
    return b.getvalue()


def c_array(name, data):
    rows = [', '.join(str(x) for x in data[i:i + 24]) for i in range(0, len(data), 24)]
    return 'static const unsigned char %s[%d] = {\n    %s\n};\n' % (name, len(data), ',\n    '.join(rows))


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'images/bossrush.png'
    dst = sys.argv[2] if len(sys.argv) > 2 else 'src/menu_art.h'
    im = Image.open(src).convert('RGBA')
    r, g, b, a = im.split()
    solid = a.point(lambda v: 255 if v >= 245 else 0).filter(ImageFilter.GaussianBlur(1.5))
    art = square(Image.merge('RGBA', (r, g, b, solid))).resize((ART, ART), Image.LANCZOS)

    sil = art.split()[3].resize((INNER, INNER), Image.LANCZOS)
    mask = Image.new('L', (GLOW, GLOW), 0)
    mask.paste(sil, ((GLOW - INNER) // 2, (GLOW - INNER) // 2))
    mask = mask.point(lambda v: 255 if v >= 96 else 0).filter(ImageFilter.MaxFilter(9)).filter(ImageFilter.GaussianBlur(4))
    glow = Image.merge('RGBA', (Image.new('L', mask.size, 255),) * 3 + (mask,))

    with open(dst, 'w', newline='\n') as f:
        f.write('/* menu_art.h - generated by tools/make_menu_art.py from %s: do not edit (port extra: the main menu\'s\n'
                ' * Boss Rumble icon, its art and its glow, as PNG bytes for render_gl.c) */\n' % src.replace('\\', '/'))
        f.write(c_array('MENU_ART_RUMBLE', png_bytes(art)))
        f.write(c_array('MENU_ART_RUMBLE_GLOW', png_bytes(glow)))
    print('wrote', dst)


if __name__ == '__main__':
    main()
